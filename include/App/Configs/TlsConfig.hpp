#pragma once

#include <string>

namespace app
{

// Настройки TLS и ссылки-приглашения. Секция целиком опциональна:
// все поля имеют дефолты, отсутствующие ключи в JSON их не трогают.
struct TlsConfig
{
    // Пути к своему сертификату/ключу (PEM). Оба пустые — сервер сам
    // сгенерирует самоподписанную пару в рабочей директории (рядом с БД)
    // и будет переиспользовать её при следующих запусках, чтобы
    // fingerprint (а значит и ссылка-приглашение) не менялся.
    // Задан только один из двух путей — ошибка конфигурации (fail-fast).
    std::string certFile;
    std::string keyFile;

    // Имя URI-схемы в ссылке-приглашении: {scheme}://host:port/#fingerprint.
    // Должно соответствовать грамматике схемы: [a-z][a-z0-9+.-]*
    std::string scheme = "zhizha";

    // Адрес (домен или IP) для ссылки. Пусто — определяется локальный IP
    // машины автоматически.
    std::string address;
};

} // namespace app
